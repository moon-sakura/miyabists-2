namespace Miyabists2.Scripts.Powers
{
    internal class MiyabiParryPower : CustomPowerModel
    {
        public override PowerType Type => PowerType.Buff;
        public override PowerStackType StackType => PowerStackType.Counter;
        public override Color AmountLabelColor => PowerModel._normalAmountLabelColor;
        public string BigIconPath => "res://images/powers/miyabiParry.png";
        public string BigBetaIconPath => BigIconPath;
        public override string CustomPackedIconPath => BigIconPath;
        public override string CustomBigIconPath => BigIconPath;

        protected override IEnumerable<IHoverTip> ExtraHoverTips =>
        [
            HoverTipFactory.FromCard<HuaCi>()
        ];


        public override async Task AfterDamageReceived(PlayerChoiceContext choiceContext, Creature target, DamageResult result, ValueProp props, Creature? dealer, CardModel? cardSource)
        {
            if (result.BlockedDamage >= 0 && base.Amount > 0 && target == base.Owner)
            {
                await MiyabiCombatService.AddHuaCiReward(target, dealer!, choiceContext, 1);

                await PowerCmd.TickDownDuration(this);
            }
        }

    }
}
